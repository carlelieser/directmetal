import json
from dataclasses import asdict

from .model import Interface, Inventory, Member

GENERATED_NOTE = "<!-- Generated by tools/api/generate_inventory.py. Do not edit. -->"


def member_label(member: Member) -> str:
    label = f"`{member.name}`"
    if member.macos:
        label += f" (macOS {member.macos})"
    if member.is_deprecated:
        label += " *(deprecated)*"
    return label


def interface_section(interface: Interface) -> list[str]:
    base = f" : `{interface.base}`" if interface.base else ""
    heading = f"### {interface.name}{base}"
    meta = f"Source: `{interface.source}` · {len(interface.members)} members"
    members = ", ".join(member_label(member) for member in interface.members) or "_none_"
    return [heading, "", meta, "", members, ""]


def summary_lines(inventory: Inventory) -> list[str]:
    return [
        f"| Interfaces / classes | {len(inventory.interfaces)} |",
        f"| Methods / properties | {inventory.method_count()} |",
        f"| Enums | {len(inventory.enums)} |",
        f"| Structs | {len(inventory.structs)} |",
        f"| Exported functions | {len(inventory.functions)} |",
    ]


def to_markdown(inventory: Inventory, provenance: str) -> str:
    lines = [
        GENERATED_NOTE,
        "",
        f"# {inventory.group} API inventory",
        "",
        provenance,
        "",
    ]
    lines += ["| Kind | Count |", "| --- | ---: |", *summary_lines(inventory), ""]
    lines += ["## Exported functions", ""]
    lines += [f"- `{name}` — `{source}`" for name, source in sorted(inventory.functions.items())]
    lines += ["", "## Interfaces", ""]
    for name in sorted(inventory.interfaces):
        lines += interface_section(inventory.interfaces[name])
    lines += ["## Enums", "", "| Enum | Members | Source |", "| --- | ---: | --- |"]
    for name in sorted(inventory.enums):
        enum = inventory.enums[name]
        lines.append(f"| `{name}` | {len(enum.members)} | `{enum.source}` |")
    lines += ["", "## Structs", ""]
    lines.append(", ".join(f"`{name}`" for name in sorted(inventory.structs)) or "_none_")
    return "\n".join(lines) + "\n"


def to_json(inventory: Inventory, provenance: str) -> str:
    document = {"group": inventory.group, "provenance": provenance, **asdict(inventory)}
    return json.dumps(document, indent=1, sort_keys=True) + "\n"
