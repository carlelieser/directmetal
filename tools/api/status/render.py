import json

from .report import METRICS, GroupStatus, MethodStatus

GENERATED_NOTE = "<!-- Generated by tools/api/report_status.py. Do not edit. -->"
TABLE_HEADER = ["| {} | Status | Tested | Source |", "| --- | --- | --- | --- |"]
EMPTY_CELL = "—"


def share(count: int, total: int) -> str:
    if total == 0:
        return EMPTY_CELL
    return f"{100 * count / total:.1f}%"


def counts_table(status: GroupStatus) -> list[str]:
    total = len(status.methods)
    lines = ["| Status | Count | Share |", "| --- | ---: | ---: |"]
    for metric, count in status.counts().items():
        lines.append(f"| {metric.capitalize()} | {count} | {share(count, total)} |")
    return [*lines, f"| Total | {total} | |"]


def method_row(label: str, method: MethodStatus) -> str:
    tested = "yes" if method.is_tested else EMPTY_CELL
    source = f"`{method.location}`" if method.location else EMPTY_CELL
    return f"| `{label}` | {method.state} | {tested} | {source} |"


def methods_table(column: str, methods: list[MethodStatus]) -> list[str]:
    header = [TABLE_HEADER[0].format(column), TABLE_HEADER[1]]
    return [*header, *(method_row(method.entry.name, method) for method in methods), ""]


def by_owner(methods: list[MethodStatus]) -> dict[str | None, list[MethodStatus]]:
    owners: dict[str | None, list[MethodStatus]] = {}
    for method in methods:
        owners.setdefault(method.entry.owner, []).append(method)
    return owners


def to_markdown(status: GroupStatus) -> str:
    lines = [GENERATED_NOTE, "", f"# {status.group} implementation status", ""]
    lines += [*counts_table(status), ""]
    owners = by_owner(status.methods)
    lines += ["## Exported functions", ""]
    lines += methods_table("Function", owners.pop(None, [])) if None in owners else ["_none_", ""]
    lines += ["## Interfaces", ""]
    for owner in sorted(owners):
        lines += [f"### {owner}", "", *methods_table("Method", owners[owner])]
    return "\n".join(lines)


def summary_markdown(statuses: list[GroupStatus]) -> str:
    columns = [metric.capitalize() for metric in METRICS]
    lines = [GENERATED_NOTE, "", "# Implementation status summary", ""]
    lines.append(f"| Group | {' | '.join(columns)} | Total |")
    lines.append("| --- |" + " ---: |" * (len(columns) + 1))
    for status in statuses:
        counts = " | ".join(str(count) for count in status.counts().values())
        lines.append(f"| [{status.group}]({status.group}.md) | {counts} | {len(status.methods)} |")
    return "\n".join(lines) + "\n"


def group_document(status: GroupStatus) -> dict:
    methods = {
        method.entry.key: {
            "state": method.state,
            "is_tested": method.is_tested,
            "location": method.location,
        }
        for method in status.methods
    }
    return {"counts": {**status.counts(), "total": len(status.methods)}, "methods": methods}


def to_json(statuses: list[GroupStatus]) -> str:
    document = {"groups": {status.group: group_document(status) for status in statuses}}
    return json.dumps(document, indent=1, sort_keys=True) + "\n"
