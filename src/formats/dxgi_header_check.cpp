constexpr bool matches_header() {
    if (std::size(header_formats) != dxgi_rows.size()) {
        return false;
    }
    for (std::size_t index = 0; index < dxgi_rows.size(); ++index) {
        const bool is_same = header_formats[index].value == dxgi_rows[index].format &&
                             header_formats[index].name == dxgi_rows[index].name;
        if (!is_same) {
            return false;
        }
    }
    return true;
}

static_assert(matches_header(), "DXGI_FORMAT rows differ from DirectX-Headers' dxgiformat.h");

